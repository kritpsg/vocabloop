/* ---------- เทียบความคล้ายของเสียงพูด (Levenshtein) ---------- */
JA.norm = s => JA.toHira(String(s)).toLowerCase().replace(/[\s、。，．！？!?,.・「」『』~〜ー]/g, '');
JA.sim = (a, b) => {
  a = JA.norm(a); b = JA.norm(b); if (!a || !b) return 0;
  const d = Array.from({ length: a.length + 1 }, (_, i) => [i, ...Array(b.length).fill(0)]);
  for (let j = 1; j <= b.length; j++) d[0][j] = j;
  for (let i = 1; i <= a.length; i++) for (let j = 1; j <= b.length; j++)
    d[i][j] = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
  return 1 - d[a.length][b.length] / Math.max(a.length, b.length);
};
JA.bestSim = (heard, targets) => Math.max(0, ...targets.filter(Boolean).map(t => JA.sim(heard, t)));

